import type { Metadata } from "next";
import { Dancing_Script, Geist, Geist_Mono } from "next/font/google";
import { Navbar } from "@/components/navbar";
import { Footer } from "@/components/footer";

import { Toaster } from "react-hot-toast";
import "./globals.css";
import ThemeProvider from "@/components/theme-provider";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

const dancingScript = Dancing_Script({
  variable: "--font-dance",
  subsets: ["latin"],
});

/** Cached so the prerender can freeze the year instead of reading it live. */
async function getCopyrightYear(): Promise<number> {
  "use cache";
  return new Date().getFullYear();
}

export const metadata: Metadata = {
  title: "Studio Space",
  description: "Generated by create Studio space",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const copyrightYear = await getCopyrightYear();

  return (
<html
  lang="en"
  className={`${geistSans.variable} ${geistMono.variable} ${dancingScript.variable} h-full antialiased`}
>
  <body className="min-h-full flex flex-col">
    <ThemeProvider>
      <Navbar />
      {children}
      <Footer year={copyrightYear} />
      <Toaster position="top-center" />
    </ThemeProvider>
  </body>
</html>
  );
}
